import sys
import os
try:
    from PIL import Image, ImageDraw
except ImportError:
    print("Pillow not installed. Run: pip install Pillow")
    sys.exit(1)

from io import BytesIO

def generate_frame(index, total_frames, width=640, height=480):
    img = Image.new('RGB', (width, height), color=(0, 0, 0))
    draw = ImageDraw.Draw(img)

    # Draw some color bars
    bar_width = width // 8
    colors = [
        (255, 255, 255), (255, 255, 0), (0, 255, 255), (0, 255, 0),
        (255, 0, 255), (255, 0, 0), (0, 0, 255), (0, 0, 0)
    ]
    for i in range(8):
        draw.rectangle([i*bar_width, 0, (i+1)*bar_width, height], fill=colors[i])

    # Draw a moving box to indicate live video
    box_size = 50
    x_pos = int((index / total_frames) * (width - box_size))
    y_pos = height // 2 - box_size // 2
    draw.rectangle([x_pos, y_pos, x_pos + box_size, y_pos + box_size], fill=(255, 255, 255), outline=(0, 0, 0))

    buf = BytesIO()
    img.save(buf, format='JPEG', quality=80)
    return buf.getvalue()

def main():
    out_dir = 'components/test_pattern_source'
    out_file = os.path.join(out_dir, 'test_pattern_data.h')

    frames = []
    num_frames = 8
    for i in range(num_frames):
        frames.append(generate_frame(i, num_frames))

    with open(out_file, 'w') as f:
        f.write('/* Auto-generated by tools/generate_test_pattern.py */\n')
        f.write('#pragma once\n\n')
        f.write(f'#define TEST_PATTERN_NUM_FRAMES {num_frames}\n\n')

        for i, frame in enumerate(frames):
            f.write(f'static const unsigned char test_pattern_frame_{i}[] = {{\n    ')
            for j, b in enumerate(frame):
                f.write(f'0x{b:02x}, ')
                if (j + 1) % 12 == 0:
                    f.write('\n    ')
            f.write('\n};\n\n')

        f.write('static const unsigned char* const test_pattern_frames[] = {\n')
        for i in range(num_frames):
            f.write(f'    test_pattern_frame_{i},\n')
        f.write('};\n\n')

        f.write('static const unsigned int test_pattern_frame_sizes[] = {\n')
        for i, frame in enumerate(frames):
            f.write(f'    {len(frame)},\n')
        f.write('};\n')

if __name__ == '__main__':
    main()
