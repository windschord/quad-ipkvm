#include "unity.h"
#include "http_guard.h"

void setUp(void) {}
void tearDown(void) {}

void test_decide_needs_setup(void) {
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_STATUS, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_SETUP, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_405, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_SETUP, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_ORIGIN, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_SETUP, false, false, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_415, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_SETUP, false, true, false));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_SETUP_REQUIRED, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGIN, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_SETUP_REQUIRED, http_guard_decide(AUTH_STATE_NEEDS_SETUP, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_OTHER, false, true, true));
}

void test_decide_ready(void) {
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_STATUS, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_SETUP_REQUIRED, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_SETUP, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGIN, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_405, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_LOGIN, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_ORIGIN, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGIN, false, false, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_415, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGIN, false, true, false));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGOUT, true, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_401, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGOUT, false, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_405, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_LOGOUT, true, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_ORIGIN, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_LOGOUT, true, false, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_OTHER, true, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_ALLOW, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_OTHER, true, true, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_403_ORIGIN, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_POST, HTTP_GUARD_PATH_OTHER, true, false, true));
    TEST_ASSERT_EQUAL(HTTP_GUARD_ACTION_401, http_guard_decide(AUTH_STATE_READY, HTTP_GUARD_METHOD_GET, HTTP_GUARD_PATH_OTHER, false, true, true));
}

int main(void) {
    UNITY_BEGIN();
    RUN_TEST(test_decide_needs_setup);
    RUN_TEST(test_decide_ready);
    return UNITY_END();
}
