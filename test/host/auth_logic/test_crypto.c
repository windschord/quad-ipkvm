#include "unity.h"
#include "auth_crypto_ref.h"
#include <string.h>

void setUp(void) {}
void tearDown(void) {}

// Test Vector 1 from RFC 4231
void test_hmac_sha256_rfc4231_tc1(void) {
    const uint8_t key[20] = {
        0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b
    };
    const char *data = "Hi There";
    uint8_t expected[32] = {
        0xb0, 0x34, 0x4c, 0x61, 0xd8, 0xdb, 0x38, 0x53, 0x5c, 0xa8,
        0xaf, 0xce, 0xaf, 0x0b, 0xf1, 0x2b, 0x88, 0x1d, 0xc2, 0x00,
        0xc9, 0x83, 0x3d, 0xa7, 0x26, 0xe9, 0x37, 0x6c, 0x2e, 0x32, 0xcf, 0xf7
    };
    uint8_t out[32];

    TEST_ASSERT_EQUAL(0, ref_crypto_if.hmac_sha256(key, sizeof(key), (const uint8_t*)data, strlen(data), out));
    TEST_ASSERT_EQUAL_HEX8_ARRAY(expected, out, 32);
}

// Test Vector from RFC 7914 (PBKDF2-HMAC-SHA256)
void test_pbkdf2_rfc7914(void) {
    const char *pass = "password";
    const char *salt = "salt";
    uint8_t expected[32] = {
        0x12, 0x0f, 0xb6, 0xcf, 0xfc, 0xf8, 0xb3, 0x2c, 0x43, 0xe7, 0x22, 0x52, 0x56, 0xc4, 0xf8, 0x37,
        0xa8, 0x65, 0x48, 0xc9, 0x2c, 0xcc, 0x35, 0x48, 0x08, 0x05, 0x98, 0x7c, 0xb7, 0x0b, 0xe1, 0x7b
    };
    uint8_t out[32];

    TEST_ASSERT_EQUAL(0, ref_crypto_if.pbkdf2_hmac_sha256((const uint8_t*)pass, strlen(pass), (const uint8_t*)salt, strlen(salt), 1, 32, out));
    TEST_ASSERT_EQUAL_HEX8_ARRAY(expected, out, 32);
}

void test_pbkdf2_rfc7914_iter2(void) {
    const char *pass = "password";
    const char *salt = "salt";
    uint8_t expected[32] = {
        0xae, 0x4d, 0x0c, 0x95, 0xaf, 0x6b, 0x46, 0xd3, 0x2d, 0x0a,
        0xdf, 0xf9, 0x28, 0xf0, 0x6d, 0xd0, 0x2a, 0x30, 0x3f, 0x8e,
        0xf3, 0xc2, 0x51, 0xdf, 0xd6, 0xe2, 0xd8, 0x5a, 0x95, 0x47, 0x4c, 0x43
    };
    uint8_t out[32];

    TEST_ASSERT_EQUAL(0, ref_crypto_if.pbkdf2_hmac_sha256((const uint8_t*)pass, strlen(pass), (const uint8_t*)salt, strlen(salt), 2, 32, out));
    TEST_ASSERT_EQUAL_HEX8_ARRAY(expected, out, 32);
}

int main(void) {
    UNITY_BEGIN();
    RUN_TEST(test_hmac_sha256_rfc4231_tc1);
    RUN_TEST(test_pbkdf2_rfc7914);
    RUN_TEST(test_pbkdf2_rfc7914_iter2);
    return UNITY_END();
}
