// Test Vector 1 from RFC 4231
void test_hmac_sha256_rfc4231_tc1(void) {
    const uint8_t key[20] = {
        0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b,
        0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b, 0x0b
    };
    const char *data = "Hi There";
    uint8_t expected[32] = {
        0xb0, 0x34, 0x4c, 0x61, 0xd8, 0xdb, 0x38, 0x53, 0x5c, 0xa8,
        0xaf, 0xce, 0xaf, 0x0b, 0xf1, 0x2b, 0x88, 0x1d, 0xc2, 0x00,
        0xc9, 0x83, 0x3d, 0xa7, 0x26, 0xe9, 0x37, 0x6c, 0x2e, 0x32, 0xcf, 0xf7
    };
    uint8_t out[32];

    TEST_ASSERT_EQUAL(0, ref_crypto_if.hmac_sha256(key, sizeof(key), (const uint8_t*)data, strlen(data), out));
    TEST_ASSERT_EQUAL_HEX8_ARRAY(expected, out, 32);
}

